"""Filter the generated /no_think data

Merges /no_think data from two sources and applies three filters:
  1. Correctness filter: compare the answer with the ground truth (math+science only)
  2. Style filter: detect reasoning behaviour (reflective words)
  3. Length filter: the output must not exceed the token limit

Input:
  - no_think_raw.jsonl (math+science, model-generated)
  - no_think_instruction.jsonl (instruction, extracted directly)

Output:
  - no_think_filtered.jsonl — samples that pass the filters (ShareGPT format)
  - rejected_uuids.jsonl   — rejected samples (UUID + rejection reason), used by Step 2 to top up
    Append mode: Step 2 has already written the samples whose generation failed; Step 3 appends the filter rejections

Usage:
    python -m src.datasets.filter_no_think_data \
        --raw_input datasets/superior_reasoning/no_think_raw.jsonl \
        --instruction_input datasets/superior_reasoning/no_think_instruction.jsonl \
        --output datasets/superior_reasoning/no_think_filtered.jsonl \
        --rejected_output datasets/superior_reasoning/rejected_uuids.jsonl

Dependencies:
    pip install transformers  (for token counting)
"""

