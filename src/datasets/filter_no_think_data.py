# ==================== Token counting ====================

# Global tokenizer (lazily loaded)
_tokenizer = None


def get_tokenizer():
    """Lazily load the tokenizer (Qwen2.5 tokenizer, used for token counting)"""
    global _tokenizer
    if _tokenizer is None:
        from transformers import AutoTokenizer
        # Use the Qwen2.5 tokenizer for token counting
        # It is downloaded automatically if it is not available locally
        _tokenizer = AutoTokenizer.from_pretrained(
            "Qwen/Qwen2.5-7B-Instruct",
            trust_remote_code=True,
        )
    return _tokenizer


def count_tokens(text: str) -> int:
    """Count the tokens of a text

    Args:
        text: input text

    Returns:
        number of tokens
    """
    tokenizer = get_tokenizer()
    return len(tokenizer.encode(text, add_special_tokens=False))


# ==================== Answer extraction ====================

def extract_boxed_answer(text: str) -> str | None:
    """Extract the answer inside \\boxed{...} from text (stack matching, nested braces supported)

    If there are several \\boxed{}, the last one is used.

    Args:
        text: text containing \\boxed{}

    Returns:
        the extracted answer string, or None if not found
    """
    pattern = r'\\boxed\s*\{'
    matches = list(re.finditer(pattern, text))
    if not matches:
        return None

    last_match = matches[-1]
    start = last_match.end()

    depth = 1
    pos = start
    while pos < len(text) and depth > 0:
        if text[pos] == '{':
            depth += 1
        elif text[pos] == '}':
            depth -= 1
        pos += 1

    if depth != 0:
        return None

    answer = text[start:pos - 1].strip()
    return answer if answer else None


def extract_answer_from_text(text: str, domain: str) -> str | None:
    """Extract the answer from generated text (try \\boxed{} first, then heuristics)

    Args:
        text: text generated by the model
        domain: data domain

    Returns:
        the extracted answer, or None if not found
    """
    # Prefer \boxed{}
    answer = extract_boxed_answer(text)
    if answer is not None:
        return answer

    # science: try to match a multiple-choice letter
    if domain == "science":
        m = re.search(r'\b([A-E])\b\s*$', text.strip())
        if m:
            return m.group(1).upper()

    # Try the "answer is X" pattern
    for pat in [
        r'(?:the\s+)?answer\s+is\s*[:\s]*(.+?)(?:\.|$)',
        r'(?:therefore|thus|hence)\s*,?\s*(.+?)(?:\.|$)',
    ]:
        m = re.search(pat, text, re.IGNORECASE)
        if m:
            return m.group(1).strip()

    # Last resort: if the text is very short, the whole text may be the answer
    stripped = text.strip()
    if len(stripped) <= 50:
        return stripped

    return None


# ==================== Answer normalization ====================

def normalize_latex(text: str) -> str:
    """Clean LaTeX formatting to make comparison easier

    Args:
        text: string containing LaTeX

    Returns:
        the normalized string
    """
    s = text.strip()

    # Remove style commands such as displaystyle, textstyle
    s = re.sub(r'\\(?:displaystyle|textstyle|scriptstyle|scriptscriptstyle)\s*', '', s)

    # Unify fraction commands: \dfrac, \tfrac, \cfrac -> \frac
    s = re.sub(r'\\[dtc]frac\b', r'\\frac', s)

    # Remove LaTeX spacing commands: \,  \;  \:  \!  \quad  \qquad  etc.
    s = re.sub(r'\\[,;:!\s]', '', s)
    s = re.sub(r'\\(?:quad|qquad|enspace|thinspace|medspace|thickspace)\b', '', s)

    # Remove wrappers such as \text{}, \mathrm{}, \textbf{}, \mathbf{}
    s = re.sub(r'\\(?:text|mathrm|textbf|mathbf|textrm|textit|mathit|mathcal|mathbb|mathfrak)\s*\{([^}]*)\}', r'\1', s)

    # Remove \left, \right
    s = re.sub(r'\\(?:left|right)\s*', '', s)

    # Remove extra spaces
    s = re.sub(r'\s+', ' ', s).strip()

    return s


def try_parse_number(text: str) -> float | None:
    """Try to parse the text as a number (supports fractions, percentages, LaTeX fractions)

    Args:
        text: a string that may be a number

    Returns:
        the parsed float, or None on failure
    """
    s = text.strip()
    s_no_comma = s.replace(',', '')

    # Try float directly
    try:
        return float(s_no_comma)
    except ValueError:
        pass

    # Try a Python fraction (e.g. 1/2)
    try:
        return float(Fraction(s_no_comma))
    except (ValueError, ZeroDivisionError):
        pass

    # Try a LaTeX fraction \frac{a}{b}
    m = re.match(r'\\frac\s*\{([^}]+)\}\s*\{([^}]+)\}', s)
    if m:
        try:
            num = float(m.group(1))
            den = float(m.group(2))
            if den != 0:
                return num / den
        except ValueError:
            pass

    # Percentage
    m = re.match(r'([\d.]+)\s*%', s)
    if m:
        try:
            return float(m.group(1)) / 100.0
        except ValueError:
            pass

    return None


def normalize_answer(answer: str) -> str:
    """Normalize an answer for comparison

    Args:
        answer: the raw answer string

    Returns:
        the normalized answer string
    """
    cleaned = normalize_latex(answer)

    # Try numeric conversion
    num = try_parse_number(cleaned)
    if num is not None and not (math.isinf(num) or math.isnan(num)):
        if num == int(num):
            return str(int(num))
        return f"{num:.10g}"

    # String normalization: lowercase, strip spaces, strip punctuation
    s = cleaned.lower().strip()
    s = re.sub(r'[.,;:!?\s]+', '', s)
    return s


# ==================== Filters ====================

# Patterns indicating reasoning behaviour (case-insensitive matching)
REASONING_PATTERNS = [
    r'\bwait\b',
    r'\blet me think\b',
    r'\blet\'s\b',
    r'\bfirst\b.*\bthen\b',
    r'\bstep \d+\b',
    r'\bhmm+\b',
    r'\bokay\b',
    r'\bwe need to\b',
    r'\bwe can\b',
    r'\bto solve this\b',
    r'\brecall that\b',
    r'\bnote that\b',
    r'\bconsider\b',
    r'\bthink\b',
    r'<think>',
]
# Precompile the regexes for performance
_COMPILED_PATTERNS = [re.compile(p, re.IGNORECASE) for p in REASONING_PATTERNS]


# Prompt for the model-based judgement
MODEL_JUDGE_PROMPT = """You are a mathematical equivalence checker. Your task is to determine if two mathematical answers are equivalent.

**Problem:**
{problem}

**Model's Complete Response:**
{full_response}

**Extracted Answer from Model:**
{generated_answer}

**Ground Truth Answer:**
{ground_truth}

Your task: Determine if the "Extracted Answer from Model" and "Ground Truth Answer" are mathematically equivalent.

Consider:
1. Different LaTeX formatting (e.g., \\frac vs \\dfrac, \\displaystyle)
2. Different variable names or representations (e.g., x=1, y=12 vs 1³+12³)
3. Approximate vs exact values (e.g., \\approx vs exact number)
4. Different but equivalent mathematical expressions
5. Use the full response and problem context to understand the answer better

Output your judgment in \\boxed{{YES}} if they are equivalent, or \\boxed{{NO}} if they are not equivalent.

Only output \\boxed{{YES}} or \\boxed{{NO}}, nothing else."""


async def check_correctness_with_model(
    generated_answer: str,
    ground_truth: str,
    full_response: str,
    problem: str,
    api_url: str,
    model_name: str,
    timeout: int = 60,
) -> bool:
    """Use a model to judge whether the answers are equivalent

    Args:
        generated_answer: the extracted generated answer
        ground_truth: the reference answer
        full_response: the model's full response
        problem: problem statement
        api_url: vLLM API URL
        model_name: model name
        timeout: timeout in seconds

    Returns:
        True if equivalent, False otherwise
    """
    prompt = MODEL_JUDGE_PROMPT.format(
        problem=problem,
        full_response=full_response,
        generated_answer=generated_answer,
        ground_truth=ground_truth,
    )

    url = f"{api_url}/chat/completions"
    payload = {
        "model": model_name,
        "messages": [
            {"role": "user", "content": prompt},
        ],
        "max_tokens": 50,
        "temperature": 0.0,
    }

    try:
        async with aiohttp.ClientSession() as session:
            async with session.post(
                url, json=payload, timeout=aiohttp.ClientTimeout(total=timeout)
            ) as resp:
                if resp.status == 200:
                    data = await resp.json()
                    content = data["choices"][0]["message"]["content"]

                    # Extract the content of \boxed{}
                    match = re.search(r'\\boxed\s*\{([^}]+)\}', content)
                    if match:
                        result = match.group(1).strip().upper()
                        return result == "YES"

                    # If there is no \boxed{}, try matching YES/NO directly
                    if "YES" in content.upper():
                        return True
                    if "NO" in content.upper():
                        return False

                    # Cannot decide; return False by default
                    return False
                else:
                    # API error; return False by default
                    return False
    except Exception:
        # Any exception; return False by default
        return False


def check_correctness(
    generated: str,
    ground_truth: str | None,
    domain: str,
    input_text: str = "",
    use_model: bool = False,
    api_url: str | None = None,
    model_name: str | None = None,
) -> bool:
    """Filter 1: correctness check

    Extracts the answer from the generated text and compares it with the normalized ground truth.
    If ground_truth is None the check is skipped (returns True).

    Optional: use a model for the equivalence judgement (handles complex mathematical equivalences)

    Args:
        generated: text generated by the model
        ground_truth: the reference answer
        domain: data domain
        input_text: problem statement
        use_model: whether to use the model judgement (optional)
        api_url: vLLM API URL (required when use_model=True)
        model_name: model name (required when use_model=True)

    Returns:
        True if it passes (the answer is correct or cannot be checked)
    """
    if ground_truth is None:
        return True

    gen_answer = extract_answer_from_text(generated, domain)
    if gen_answer is None:
        return False

    # Try the rule-based normalized comparison first
    if normalize_answer(gen_answer) == normalize_answer(ground_truth):
        return True

    # If the rule-based check fails and the model judgement is enabled, use the model
    if use_model and api_url and model_name:
        # Note: this is a synchronous function that calls an asynchronous one
        # so asyncio.run() is needed at the call site
        try:
            loop = asyncio.get_event_loop()
        except RuntimeError:
            loop = asyncio.new_event_loop()
            asyncio.set_event_loop(loop)

        return loop.run_until_complete(
            check_correctness_with_model(
                generated_answer=gen_answer,
                ground_truth=ground_truth,
                full_response=generated,
                problem=input_text,
                api_url=api_url,
                model_name=model_name,
            )
        )

    return False


def check_no_reasoning_style(text: str) -> bool:
    """Filter 2: style check (no reasoning behaviour)

    Detects reasoning/reflective words in the text.

    Args:
        text: text generated by the model

    Returns:
        True if it passes (no reasoning behaviour)
    """
    for pattern in _COMPILED_PATTERNS:
        if pattern.search(text):
            return False
    return True


def check_token_length(text: str, max_tokens: int) -> bool:
    """Filter 3: token length check

    Args:
        text: text generated by the model
        max_tokens: maximum number of tokens

    Returns:
        True if it passes (the token count is within the limit)
    """
    return count_tokens(text.strip()) <= max_tokens


# ==================== Main ====================

def main():
    parser = argparse.ArgumentParser(
        description="Filter /no_think data (correctness + style + token length)"
    )
    parser.add_argument(
        "--raw_input",
        type=str,
        default="datasets/superior_reasoning/no_think_raw.jsonl",
        help="Path to the raw model-generated /no_think data (math+science)",
    )
    parser.add_argument(
        "--instruction_input",
        type=str,
        default="datasets/superior_reasoning/no_think_instruction.jsonl",
        help="Path to the /no_think data extracted directly from the instruction domain",
    )
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="Output path after filtering (default: same directory as raw_input, file name *_filtered.jsonl)",
    )
    parser.add_argument(
        "--rejected_output",
        type=str,
        default=None,
        help="Output path for the list of rejected UUIDs (default: same directory as raw_input, file name rejected_uuids.jsonl)",
    )
    parser.add_argument("--max_tokens_math", type=int, default=800, help="Maximum tokens for math (default: 800)")
    parser.add_argument("--max_tokens_science", type=int, default=800, help="Maximum tokens for science (default: 800)")
    parser.add_argument("--max_tokens_instruction", type=int, default=500, help="Maximum tokens for instruction (default: 500)")
    parser.add_argument("--skip_correctness", action="store_true", help="Skip the correctness filter")
    parser.add_argument("--skip_style", action="store_true", help="Skip the style filter")
    parser.add_argument("--skip_length", action="store_true", help="Skip the length filter")
    parser.add_argument(
        "--use_model_judge",
        action="store_true",
        help="Use a model to judge answer equivalence (optional, handles complex mathematical equivalences)",
    )
    parser.add_argument(
        "--judge_api_url",
        type=str,
        default="http://localhost:8000/v1",
        help="Model-judge API URL (required when use_model_judge=True)",
    )
    parser.add_argument(
        "--judge_model_name",
        type=str,
        default="Qwen3-32B",
        help="Model name used for the judgement (required when use_model_judge=True)",
    )
    parser.add_argument(
        "--suffix",
        type=str,
        default=None,
        help="Output file name suffix (e.g. retry1), used to avoid overwriting existing files",
    )
    args = parser.parse_args()

    raw_input_path = project_root / args.raw_input
    instruction_input_path = project_root / args.instruction_input

    # Build the suffix string
    suffix_str = f"_{args.suffix}" if args.suffix else ""

    # Output path: default is the same directory as raw_input, file name *_filtered[_suffix].jsonl
    if args.output:
        output_path = project_root / args.output
    else:
        output_path = raw_input_path.parent / (raw_input_path.stem + f"_filtered{suffix_str}.jsonl")

    # Rejected output path: default is the same directory as raw_input, file name rejected_uuids[_suffix].jsonl
    if args.rejected_output:
        rejected_path = project_root / args.rejected_output
    else:
        rejected_path = raw_input_path.parent / f"rejected_uuids{suffix_str}.jsonl"

    output_path.parent.mkdir(parents=True, exist_ok=True)

    max_tokens = {
        "math": args.max_tokens_math,
        "science": args.max_tokens_science,
        "instruction-following": args.max_tokens_instruction,
    }

    print(f"\n{'='*60}")
    print("Step 3: Filter /no_think data")
    print(f"{'='*60}")
    print(f"Raw input (math+science):     {raw_input_path}")
    print(f"Instruction input:            {instruction_input_path}")
    print(f"Output: {output_path}")
    print(f"Rejected output: {rejected_path} (append mode)")
    print(f"Token length limit: {max_tokens}")
    print(f"Skip correctness: {args.skip_correctness}")
    print(f"Skip style:       {args.skip_style}")
    print(f"Skip length:      {args.skip_length}")
    if args.use_model_judge:
        print(f"Model judgement: enabled")
        print(f"  API URL:  {args.judge_api_url}")
        print(f"  Model:     {args.judge_model_name}")
    else:
        print(f"Model judgement: disabled (rule-based only)")

    # ---- 1. Load data ----
    print(f"\n{'─'*40}")
    print("1. Loading data...")

    # Load the raw math+science generated data
    raw_items = []
    if raw_input_path.exists():
        with open(raw_input_path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line:
                    raw_items.append(json.loads(line))
    print(f"  math+science raw data: {len(raw_items)} items")

    # Load the directly extracted instruction data
    instruction_items = []
    if instruction_input_path.exists():
        with open(instruction_input_path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line:
                    instruction_items.append(json.loads(line))
    print(f"  instruction data: {len(instruction_items)} items")

    # ---- 2. Filter math+science ----
    print(f"\n{'─'*40}")
    print("2. Filtering math+science data...")

    # Print the output length distribution (helps tune the thresholds)
    if raw_items:
        lengths = [count_tokens(it.get("generated_output", "").strip()) for it in raw_items[:1000]]
        if lengths:
            lengths_sorted = sorted(lengths)
            n = len(lengths_sorted)
            print(f"\n  Output token length distribution (first {n} sampled):")
            for p in [25, 50, 75, 90, 95, 99]:
                idx = min(int(n * p / 100), n - 1)
                print(f"    P{p}: {lengths_sorted[idx]} tokens")

    # Statistics counters
    total = 0
    pass_all = 0
    domain_stats = {}
    filtered_items = []
    rejected_items = []

    for item in raw_items:
        total += 1
        domain = item.get("domain", "unknown")
        generated = item.get("generated_output", "")
        ground_truth = item.get("ground_truth")
        uuid = item.get("uuid", "")
        input_text = item.get("input", "")

        # Initialize per-domain statistics
        if domain not in domain_stats:
            domain_stats[domain] = {
                "total": 0, "pass_correctness": 0,
                "pass_style": 0, "pass_length": 0, "pass_all": 0,
            }
        domain_stats[domain]["total"] += 1

        # Filter 1: correctness
        ok_correct = True if args.skip_correctness else check_correctness(
            generated, ground_truth, domain,
            input_text=input_text,
            use_model=args.use_model_judge,
            api_url=args.judge_api_url if args.use_model_judge else None,
            model_name=args.judge_model_name if args.use_model_judge else None,
        )
        if ok_correct:
            domain_stats[domain]["pass_correctness"] += 1

        # Filter 2: style
        ok_style = True if args.skip_style else check_no_reasoning_style(generated)
        if ok_style:
            domain_stats[domain]["pass_style"] += 1

        # Filter 3: token length
        domain_max = max_tokens.get(domain, 800)
        ok_length = True if args.skip_length else check_token_length(generated, domain_max)
        if ok_length:
            domain_stats[domain]["pass_length"] += 1

        # All passed
        if ok_correct and ok_style and ok_length:
            pass_all += 1
            domain_stats[domain]["pass_all"] += 1
            filtered_items.append(item)
        else:
            # Record the rejection reason (the first failing reason)
            if not ok_correct:
                reason = "correctness"
            elif not ok_style:
                reason = "style"
            else:
                reason = "length"
            rejected_items.append({
                "uuid": uuid,
                "domain": domain,
                "reason": reason,
                "input": input_text,
            })

        # Progress
        if total % 50000 == 0:
            print(f"  Processed: {total}/{len(raw_items)}...")

    # ---- 3. Filter instruction ----
    print(f"\n{'─'*40}")
    print("3. Filtering instruction data...")

    instruction_pass = 0
    instruction_total = 0
    if "instruction-following" not in domain_stats:
        domain_stats["instruction-following"] = {
            "total": 0, "pass_correctness": 0,
            "pass_style": 0, "pass_length": 0, "pass_all": 0,
        }

    for item in instruction_items:
        instruction_total += 1
        domain_stats["instruction-following"]["total"] += 1
        uuid = item.get("uuid", "")
        domain = item.get("domain", "instruction-following")

        # Extract the assistant answer from the ShareGPT format
        conversations = item.get("conversations", [])
        assistant_text = ""
        input_text = ""
        for conv in conversations:
            if conv.get("from") == "assistant":
                assistant_text = conv.get("value", "")
            elif conv.get("from") == "user":
                input_text = conv.get("value", "")

        # instruction has no correctness check
        domain_stats["instruction-following"]["pass_correctness"] += 1

        # Style filter
        ok_style = True if args.skip_style else check_no_reasoning_style(assistant_text)
        if ok_style:
            domain_stats["instruction-following"]["pass_style"] += 1

        # Token length filter
        inst_max = max_tokens.get("instruction-following", 500)
        ok_length = True if args.skip_length else check_token_length(assistant_text, inst_max)
        if ok_length:
            domain_stats["instruction-following"]["pass_length"] += 1

        if ok_style and ok_length:
            instruction_pass += 1
            domain_stats["instruction-following"]["pass_all"] += 1
            # Already in ShareGPT format; keep as is
            filtered_items.append(item)
        else:
            reason = "style" if not ok_style else "length"
            rejected_items.append({
                "uuid": uuid,
                "domain": domain,
                "reason": reason,
                "input": input_text,
            })

    print(f"  instruction passed: {instruction_pass}/{instruction_total}")

    # ---- 4. Write the filtered data ----
    print(f"\n{'─'*40}")
    print("4. Writing filtered data...")

    with open(output_path, "w", encoding="utf-8") as f:
        for item in filtered_items:
            # math+science must be converted to the ShareGPT format
            if "generated_output" in item:
                sharegpt = {
                    "conversations": [
                        {"from": "user", "value": f"{item['input']}/no_think"},
                        {"from": "assistant", "value": item["generated_output"]},
                    ]
                }
                f.write(json.dumps(sharegpt, ensure_ascii=False) + "\n")
            else:
                # instruction is already in ShareGPT format (with extra fields such as uuid, domain)
                # keep only the conversations field
                sharegpt = {"conversations": item["conversations"]}
                f.write(json.dumps(sharegpt, ensure_ascii=False) + "\n")

    print(f"  Wrote {len(filtered_items)} items")

    # ---- 5. Write the rejected UUIDs to rejected_uuids.jsonl ----
    print(f"\n{'─'*40}")
    print("5. Writing rejected UUIDs...")

    # Idempotent write: first load the existing Step 2 entries (reason generation_failed_*) and keep them
    # Step 3 entries are rewritten on every run, so repeated runs do not produce duplicate UUIDs
    existing_step2_items = []
    if rejected_path.exists():
        with open(rejected_path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line:
                    entry = json.loads(line)
                    # Keep the generation-failure entries written by Step 2 (reason starts with generation_failed)
                    if entry.get("reason", "").startswith("generation_failed"):
                        existing_step2_items.append(entry)
        print(f"  Kept Step 2 generation-failure entries: {len(existing_step2_items)}")

    # Write mode: Step 2 entries + new Step 3 entries
    with open(rejected_path, "w", encoding="utf-8") as f:
        for item in existing_step2_items:
            f.write(json.dumps(item, ensure_ascii=False) + "\n")
        for item in rejected_items:
            f.write(json.dumps(item, ensure_ascii=False) + "\n")

    print(f"  Wrote {len(existing_step2_items)} Step 2 entries + {len(rejected_items)} Step 3 filter-rejection records")

    # ---- 6. Print the statistics report ----
    print(f"\n{'─'*40}")
    print("6. Filter statistics report")

    total_all = total + instruction_total
    total_pass = pass_all + instruction_pass
    print(f"\n  Total samples: {total_all}")
    print(f"  All passed: {total_pass}/{total_all} ({total_pass/max(total_all,1)*100:.1f}%)")
    print(f"  Rejected:   {len(rejected_items)}")

    print(f"\n  Pass rate per domain:")
    for domain, ds in sorted(domain_stats.items()):
        dt = ds["total"]
        dp = ds["pass_all"]
        print(f"    {domain}: {dp}/{dt} ({dp/max(dt,1)*100:.1f}%)")
        print(f"      correctness: {ds['pass_correctness']}/{dt}, "
              f"style: {ds['pass_style']}/{dt}, "
              f"length: {ds['pass_length']}/{dt}")

    # Rejection reason distribution
    reason_counts = {}
    for item in rejected_items:
        key = f"{item['domain']}:{item['reason']}"
        reason_counts[key] = reason_counts.get(key, 0) + 1
    if reason_counts:
        print(f"\n  Rejection reason distribution:")
        for key, count in sorted(reason_counts.items(), key=lambda x: -x[1]):
            print(f"    {key}: {count}")

